ALTER TABLE users ADD COLUMN verified_at TIMESTAMP WITH TIME ZONE;

UPDATE alembic_version SET version_num='0006_user_verified_at' WHERE alembic_version.version_num = '0005_user_email_suppression';

-- Running upgrade 0006_user_verified_at -> 0007_user_stripe_customer_id

ALTER TABLE users ADD COLUMN stripe_customer_id VARCHAR(255);

ALTER TABLE users ADD CONSTRAINT uq_users_stripe_customer_id UNIQUE (stripe_customer_id);

