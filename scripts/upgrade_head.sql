-- Running upgrade 0007_user_stripe_customer_id -> 0008_billing_events_downgrade

ALTER TABLE users ADD COLUMN tier_downgrade_reason VARCHAR(64);

CREATE TABLE billing_events (
    id UUID NOT NULL,
    user_id VARCHAR(128) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    old_tier VARCHAR(16) NOT NULL,
    new_tier VARCHAR(16) NOT NULL,
    reason TEXT,
    stripe_event_id VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id)
);

CREATE INDEX ix_billing_events_user_created ON billing_events (user_id, created_at);

CREATE INDEX ix_billing_events_stripe_event_id ON billing_events (stripe_event_id);

