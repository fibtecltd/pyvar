"""scripts/sync_portal_seo.py: keep the portal's crawlable page links and its sitemap in step with its pages.

Reasoning:
- Search Console (exports of 2026-11-09) showed 15 of the 19 sitemap pages "Discovered - currently not
  indexed", never crawled, and a month with no change. Nothing technical blocked them (200s, canonicals,
  robots, no bot rules), so the likely cause is crawl priority, and the site gave Google little to go on:
  the nav and the footer are written by `document.write` scripts (pyvar.js), so the static HTML had no
  links between pages beyond the homepage's, each domain page had one inbound link, `local.html` had none,
  and every page linked home as `index.html`, a duplicate of `/` (the one "alternate page with proper
  canonical tag" in the reports).
- This script owns the three fixes that have to stay consistent:
  1. A plain-HTML "all pages" block (<nav class="site-links">) above the JS footer on every page, generated
     from one list, so a crawler that does not run scripts still finds a link to every page.
  2. `<lastmod>` in sitemap.xml, from the last git commit of each page (or today, for a page with
     uncommitted changes). Google uses lastmod only when it is accurate, so it is never invented.
  3. A check that every page is canonical to its own www URL, is in the sitemap, carries the block, and
     never links home as `index.html` (the home link is `/`, which is what the canonical names).
- The checker needs no git, because the pipeline's CodeBuild gets a file snapshot, not a checkout (the
  tests call it). Generating lastmod does need git, so it is a developer step: run this script after
  changing a page, then commit. A stale lastmod is ignored by Google, not an error.
- dashboard.html is left out on purpose: robots.txt disallows it and it is not in the sitemap.

Usage:
    python scripts/sync_portal_seo.py            # rewrite the block in each page and sitemap.xml
    python scripts/sync_portal_seo.py --check    # list problems, exit 1 if any (no writes, no git)
"""

from __future__ import annotations

import argparse
import datetime
import html
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORTAL = ROOT / "portal"
BASE = "https://www.pyvar.com/"
FOOTER_CALL = "<script>document.write(buildFooter())</script>"
BLOCK_RE = re.compile(r"<!-- site-links:start.*?<!-- site-links:end -->", re.DOTALL)
EXCLUDED = {"dashboard.html"}

# Title and links of each column of the block. index.html is served, linked and canonicalised as "/".
GROUPS: list[tuple[str, list[tuple[str, str]]]] = [
    (
        "Start",
        [
            ("index.html", "Home"),
            ("plugins.html", "Claude Code plugins"),
            ("local.html", "pyvar Local (offline)"),
            ("guides.html", "All guides"),
        ],
    ),
    (
        "Domains",
        [
            ("domain-market-risk.html", "Market Risk"),
            ("domain-credit-risk.html", "Credit Risk"),
            ("domain-liquidity-risk.html", "Liquidity Risk"),
            ("domain-operational-risk.html", "Operational Risk"),
            ("domain-portfolio-analytics.html", "Portfolio Analytics"),
            ("domain-regulatory.html", "Regulatory & Compliance"),
            ("domain-derivatives.html", "Derivatives & Pricing"),
            ("domain-alm.html", "ALM & Balance Sheet"),
        ],
    ),
    (
        "Guides",
        [
            ("guide-rest-api.html", "REST API"),
            ("guide-pyvar-client.html", "Python SDK"),
            ("guide-pyvar-jupyter.html", "Jupyter"),
            ("guide-claude-plugins.html", "Claude plugins guide"),
            ("guide-technical-deepdive.html", "Compute engine"),
        ],
    ),
    (
        "Legal",
        [("privacy.html", "Privacy policy"), ("terms.html", "Terms of service")],
    ),
]
PAGES = [name for _, items in GROUPS for name, _ in items]


def url_of(name: str) -> str:
    return BASE if name == "index.html" else BASE + name


def href_of(name: str) -> str:
    return "/" if name == "index.html" else name


def render_block() -> str:
    cols = []
    for title, items in GROUPS:
        links = "".join(f'<a href="{href_of(n)}">{html.escape(label)}</a>' for n, label in items)
        cols.append(
            f'<div class="site-links-col"><span class="site-links-title">{title}</span>{links}</div>'
        )
    body = "\n".join("    " + c for c in cols)
    return (
        "<!-- site-links:start (generated by scripts/sync_portal_seo.py; edit the script, not this block) -->\n"
        '<nav class="site-links" aria-label="All pages">\n'
        '  <div class="container">\n'
        f"{body}\n"
        "  </div>\n"
        "</nav>\n"
        "<!-- site-links:end -->"
    )


def with_block(text: str) -> str:
    """The page with the current block in place: replaced if present, else put above the footer script."""
    block = render_block()
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _m: block, text, count=1)
    if text.count(FOOTER_CALL) != 1:
        raise ValueError(f"expected exactly one {FOOTER_CALL!r}")
    return text.replace(FOOTER_CALL, block + "\n" + FOOTER_CALL)


def portal_pages(portal: Path) -> list[Path]:
    return sorted(p for p in portal.glob("*.html") if p.name not in EXCLUDED)


def read_sitemap(portal: Path) -> list[dict[str, str]]:
    xml = (portal / "sitemap.xml").read_text(encoding="utf-8")
    out = []
    for block in re.findall(r"<url>(.*?)</url>", xml, re.DOTALL):
        entry = {
            tag: m.group(1).strip()
            for tag in ("loc", "lastmod", "changefreq", "priority")
            if (m := re.search(rf"<{tag}>(.*?)</{tag}>", block, re.DOTALL))
        }
        out.append(entry)
    return out


def _today() -> str:
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def git_lastmod(name: str) -> str:
    """Date of the page's last commit, or today if it has uncommitted changes or git is not usable."""
    rel = f"portal/{name}"
    try:
        dirty = (
            subprocess.run(["git", "diff", "--quiet", "HEAD", "--", rel], cwd=ROOT).returncode != 0
        )
        if dirty:
            return _today()
        out = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", rel],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        return out or _today()
    except (OSError, subprocess.CalledProcessError):
        return _today()


def render_sitemap(entries: list[dict[str, str]]) -> str:
    rows = []
    for e in entries:
        fields = [f"    <loc>{e['loc']}</loc>", f"    <lastmod>{e['lastmod']}</lastmod>"]
        for tag in ("changefreq", "priority"):
            if tag in e:
                fields.append(f"    <{tag}>{e[tag]}</{tag}>")
        rows.append("  <url>\n" + "\n".join(fields) + "\n  </url>")
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows)
        + "\n</urlset>\n"
    )


def problems(portal: Path = PORTAL) -> list[str]:
    """Everything out of step in `portal`, as readable lines. Needs no git."""
    found: list[str] = []
    files = {p.name for p in portal_pages(portal)}
    if files != set(PAGES):
        found.append(f"pages differ from the list in this script: {sorted(files ^ set(PAGES))}")
    block = render_block()
    for name in sorted(files & set(PAGES)):
        text = (portal / name).read_text(encoding="utf-8")
        canonical = re.search(r'<link rel="canonical" href="([^"]+)"', text)
        if not canonical or canonical.group(1) != url_of(name):
            found.append(
                f"{name}: canonical is {canonical.group(1) if canonical else None}, want {url_of(name)}"
            )
        match = BLOCK_RE.search(text)
        if not match or match.group(0) != block:
            found.append(f"{name}: the all-pages block is missing or stale")
        if re.search(r'href=["\']index\.html', text):
            found.append(f"{name}: links home as index.html (use /)")
    js = (portal / "pyvar.js").read_text(encoding="utf-8")
    if re.search(r"""href(=|:\s*)["']index\.html""", js):
        found.append("pyvar.js: links home as index.html (use /)")
    entries = read_sitemap(portal)
    locs = [e.get("loc", "") for e in entries]
    if len(set(locs)) != len(locs):
        found.append("sitemap.xml: a URL is listed twice")
    if set(locs) != {url_of(n) for n in PAGES}:
        found.append(
            f"sitemap.xml: URLs differ from the pages: {sorted(set(locs) ^ {url_of(n) for n in PAGES})}"
        )
    today = datetime.datetime.now(datetime.timezone.utc).date()
    for e in entries:
        try:
            when = datetime.date.fromisoformat(e.get("lastmod", ""))
        except ValueError:
            found.append(f"sitemap.xml: {e.get('loc')} has no valid lastmod")
            continue
        if when > today:
            found.append(f"sitemap.xml: {e['loc']} lastmod {when} is in the future")
    return found


def sync(portal: Path = PORTAL) -> None:
    for page in portal_pages(portal):
        if page.name in PAGES:
            page.write_text(with_block(page.read_text(encoding="utf-8")), encoding="utf-8")
    old = {e["loc"]: e for e in read_sitemap(portal)}
    ordered = [url for url in old if url in {url_of(n) for n in PAGES}]
    ordered += [url_of(n) for n in PAGES if url_of(n) not in old]
    by_url = {url_of(n): n for n in PAGES}
    entries = []
    for url in ordered:
        e = dict(old.get(url, {"loc": url, "changefreq": "monthly", "priority": "0.7"}))
        e["lastmod"] = git_lastmod(by_url[url])
        entries.append(e)
    (portal / "sitemap.xml").write_text(render_sitemap(entries), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="list problems, write nothing, exit 1 if any"
    )
    args = parser.parse_args()
    if not args.check:
        sync()
    found = problems()
    for line in found:
        print(line, file=sys.stderr)
    if not found:
        print("portal pages, links and sitemap are in step")
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main())
