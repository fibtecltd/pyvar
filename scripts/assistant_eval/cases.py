"""Build the Phase 0 case set for the portal assistant eval.

Reasoning:
- The assistant is menu-driven (docs/plan-portal-ai-assistant.md, section 9): a visitor picks a function
  and an action from fixed menus and types nothing. So a "case" is one menu selection, not a free-text
  question, and the set can be built from our own data instead of guessed: every function in
  portal/functions.json, grouped as the skills group them (scripts/skill_specs/*.json), with the live
  OpenAPI request schema for the example-values action.
- Four actions are generated by the model: explain, when to use, example values (typical and stress), and
  compare with a sibling. Everything else in the menus (getting started, limits, install) is static text.
- Selection is deterministic (a hash of seed and name), so a re-run asks the same questions. It is a
  stratified sample by domain plus every function that has a tested worked example in a skill (those carry a
  known-good request body, used by the oracle). Pass --all to build the whole 385-function set.
- Ground truth: there is none for prose; the programmatic graders check what can be checked against the
  record (graders.py) and judge.py samples the rest. The only gold is the worked examples' request bodies,
  which tests/test_skill_examples.py proves the API accepts.

Usage (needs the project environment, because it imports the app to read the OpenAPI schema):
    APP_ENV=test python scripts/assistant_eval/cases.py --out /tmp/assistant_eval/cases.jsonl
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from body_schema import inline_refs  # noqa: E402

SEED = 20261107
DESCRIPTION_LIMIT = 1500
EXAMPLE_SCENARIOS = ("typical", "stress")


def load_catalogue() -> list[dict[str, Any]]:
    data: list[dict[str, Any]] = json.loads((REPO / "portal" / "functions.json").read_text())
    return data


def load_specs() -> list[dict[str, Any]]:
    paths = sorted((REPO / "scripts" / "skill_specs").glob("*.json"))
    return [json.loads(p.read_text()) for p in paths]


def gold_requests(specs: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """function name -> a request body the API is known to accept (first worked example per function)."""
    gold: dict[str, dict[str, Any]] = {}
    for spec in specs:
        for example in spec.get("examples", []):
            for call in example.get("calls", []):
                request = call.get("request")
                if isinstance(request, dict) and "<returns" not in json.dumps(request):
                    gold.setdefault(call["function"], request)
    return gold


def group_index(specs: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """function name -> {"group": title, "members": [function names in that group]}."""
    index: dict[str, dict[str, Any]] = {}
    for spec in specs:
        for group in spec.get("groups", []):
            for name in group["functions"]:
                index[name] = {"group": group["title"], "members": list(group["functions"])}
    return index


def trim_record(entry: dict[str, Any]) -> dict[str, Any]:
    """The part of a catalogue entry a model is shown (and the only part it may rely on)."""
    formula = entry.get("formula") or {}
    return {
        "name": entry["name"],
        "display_name": entry["display_name"],
        "domain": entry["domain_label"],
        "summary": entry["summary"],
        "description": (entry.get("description") or "")[:DESCRIPTION_LIMIT],
        "parameters": [
            {
                "name": p["name"],
                "type": p["type"],
                "required": p["required"],
                "default": p["default"],
                "description": p.get("description"),
            }
            for p in entry["params"]
        ],
        "formula_latex": formula.get("formula_latex"),
        "symbol_map": formula.get("symbol_map"),
        "caveat": formula.get("caveat"),
        "citation": formula.get("citation"),
    }


def _rank(name: str) -> str:
    return hashlib.sha256(f"{SEED}:{name}".encode()).hexdigest()


def pick_functions(
    catalogue: list[dict[str, Any]], gold: dict[str, Any], per_domain: int | None
) -> list[dict[str, Any]]:
    if per_domain is None:
        return sorted(catalogue, key=lambda e: e["name"])
    chosen: dict[str, dict[str, Any]] = {}
    by_domain: dict[str, list[dict[str, Any]]] = {}
    for entry in catalogue:
        by_domain.setdefault(entry["domain"], []).append(entry)
    for entries in by_domain.values():
        for entry in sorted(entries, key=lambda e: _rank(e["name"]))[:per_domain]:
            chosen[entry["name"]] = entry
    for entry in catalogue:
        if entry["name"] in gold:
            chosen[entry["name"]] = entry
    return sorted(chosen.values(), key=lambda e: e["name"])


def build_cases(
    catalogue: list[dict[str, Any]],
    specs: list[dict[str, Any]],
    schemas: dict[str, dict[str, Any]],
    per_domain: int | None = 15,
    pairs: int = 40,
) -> list[dict[str, Any]]:
    """The menu selections to evaluate.

    Args:
        catalogue: portal/functions.json.
        specs: scripts/skill_specs/*.json (groups and worked examples).
        schemas: function name -> its inlined request-body JSON schema.
        per_domain: functions sampled per domain, or None for all of them.
        pairs: how many "compare with" selections to add (same-group neighbours).

    Returns:
        Case dicts with id, intent, scenario, record, siblings, other, schema, gold, tags.
    """
    gold = gold_requests(specs)
    groups = group_index(specs)
    by_name = {e["name"]: e for e in catalogue}
    cases: list[dict[str, Any]] = []
    sampled = pick_functions(catalogue, gold, per_domain)

    def siblings_of(name: str) -> list[dict[str, str]]:
        members = [m for m in groups.get(name, {}).get("members", []) if m != name and m in by_name]
        return [{"name": m, "summary": by_name[m]["summary"]} for m in members]

    for entry in sampled:
        name = entry["name"]
        base = {
            "record": trim_record(entry),
            "siblings": siblings_of(name),
            "other": None,
            "group": groups.get(name, {}).get("group"),
        }
        tags = [entry["domain"]]
        cases.append(
            {**base, "id": f"{name}:explain", "intent": "explain", "tags": tags + ["explain"]}
        )
        cases.append({**base, "id": f"{name}:when", "intent": "when", "tags": tags + ["when"]})
        for scenario in EXAMPLE_SCENARIOS:
            cases.append(
                {
                    **base,
                    "id": f"{name}:example:{scenario}",
                    "intent": "example",
                    "scenario": scenario,
                    "schema": schemas[name],
                    "gold": gold.get(name),
                    "tags": tags + ["example", scenario],
                }
            )

    paired = 0
    for entry in sampled:
        if paired >= pairs:
            break
        name = entry["name"]
        neighbours = [s["name"] for s in siblings_of(name)]
        if not neighbours:
            continue
        other = min(neighbours, key=_rank)
        cases.append(
            {
                "id": f"{name}:compare:{other}",
                "intent": "compare",
                "record": trim_record(entry),
                "siblings": siblings_of(name),
                "other": trim_record(by_name[other]),
                "group": groups[name]["group"],
                "tags": [entry["domain"], "compare"],
            }
        )
        paired += 1
    return cases


def schemas_from_openapi(spec: dict[str, Any], catalogue: list[dict[str, Any]]) -> dict[str, Any]:
    components = spec.get("components", {}).get("schemas", {})
    out: dict[str, Any] = {}
    for entry in catalogue:
        operation = spec["paths"][entry["path"]]["post"]
        body = operation["requestBody"]["content"]["application/json"]["schema"]
        out[entry["name"]] = inline_refs(body, components)
    return out


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--out", required=True, help="where to write cases.jsonl")
    parser.add_argument("--per-domain", type=int, default=15)
    parser.add_argument("--pairs", type=int, default=40)
    parser.add_argument("--all", action="store_true", help="every function, not a sample")
    args = parser.parse_args()

    sys.path.insert(0, str(REPO))
    from main import create_app  # imported late: needs the project environment

    catalogue = load_catalogue()
    schemas = schemas_from_openapi(create_app().openapi(), catalogue)
    cases = build_cases(
        catalogue,
        load_specs(),
        schemas,
        per_domain=None if args.all else args.per_domain,
        pairs=args.pairs if not args.all else 10_000,
    )
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(json.dumps(c, sort_keys=True) + "\n" for c in cases))
    counts: dict[str, int] = {}
    for case in cases:
        counts[case["intent"]] = counts.get(case["intent"], 0) + 1
    print(f"wrote {len(cases)} cases to {out}: {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
